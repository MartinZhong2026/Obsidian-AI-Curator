let language: 'en' | 'zh' = 'en';
export function setUiLanguage(locale: string) { language = locale.toLowerCase().startsWith('zh') ? 'zh' : 'en'; }
export function uiLanguage() { return language; }
export function translate(key: string, ...values: unknown[]): string {
  const template = language === 'zh' ? ZH[key] ?? key : key;
  return template.replace(/\{(\d+)\}/g, (_, n) => String(values[Number(n)] ?? ''));
}
