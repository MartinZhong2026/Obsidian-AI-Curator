export function labels(lang: OutputLanguage) { return L[lang] ?? L.en; }

const CALLOUT: Record<Verdict, string> = { read: 'tip', skim: 'info', reference: 'note', skip: 'quote' };

/** A file name that is valid on Windows, macOS, Linux, iOS and Android and inside wikilinks. */
export function safeFileName(title: string, max = 80): string {
  const cleaned = title
    .replace(/[\\/:*?"<>|#^[\]{}%]/g, ' ')
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^\.+/, '')
    .replace(/[. ]+$/, '');
  const short = [...cleaned].slice(0, max).join('').trim();
  const reserved = /^(con|prn|aux|nul|com\d|lpt\d)$/i.test(short);
  return !short || reserved ? 'Untitled' : short;
}

/** YAML scalar: JSON strings are valid YAML double-quoted scalars. */
function y(value: string | number | boolean): string {
  return typeof value === 'string' ? JSON.stringify(value) : String(value);
}

function yamlList(values: string[]): string {
  return '[' + values.map((v) => JSON.stringify(v)).join(', ') + ']';
}

function linkTarget(path: string): string {
  return path.replace(/\.md$/i, '');
}

function aliasText(text: string): string {
  return text.replace(/[|\]\[]/g, ' ').replace(/\s+/g, ' ').trim();
}

export function wikilink(path: string, alias?: string): string {
  return alias ? `[[${linkTarget(path)}|${aliasText(alias)}]]` : `[[${linkTarget(path)}]]`;
}

function oneLine(text: string): string {
  return text.replace(/\s*\n\s*/g, ' ').trim();
}

function bullets(items: string[], checkbox = false): string {
  return items.map((i) => (checkbox ? '- [ ] ' : '- ') + oneLine(i)).join('\n');
}

function cell(text: string): string {
  return oneLine(text).replace(/\|/g, '\\|');
}

/** A fence that cannot be closed by the content itself. */
function fenced(content: string, lang = ''): string {
  const longest = Math.max(2, ...[...content.matchAll(/`{3,}|~{3,}/g)].map((m) => m[0].length));
  const fence = '`'.repeat(longest + 1);
  return `${fence}${lang}\n${content.replace(/\s+$/, '')}\n${fence}`;
}

function fenceLang(a: Asset): string {
  if (a.kind === 'prompt' || a.kind === 'template' || a.kind === 'checklist') return 'text';
  if (a.kind === 'command') return 'bash';
  return '';
}

export function formatStars(n: number): string {
  return n >= 10000 ? (n / 1000).toFixed(n >= 100000 ? 0 : 1) + 'k' : n.toLocaleString('en-US');
}

export function repoLine(f: RepoFacts, lang: OutputLanguage): string {
  const t = labels(lang);
  const bits = [`★ ${formatStars(f.stars)}`, f.language, f.license, f.pushedAt ? `${t.lastPush} ${f.pushedAt.slice(0, 10)}` : '', f.archived ? 'archived' : '']
    .filter(Boolean).join(' · ');
  return `**[${f.name}](${f.url})** · ${bits}${f.description ? ` — ${oneLine(f.description)}` : ''} _(${t.repoFacts(f)})_`;
}

export interface RelatedRef { path: string; title: string }

export interface NoteInput {
  item: Item;
  analysis: Analysis;
  lang: OutputLanguage;
  related: RelatedRef[];
  analyzedAt: number;
  model: string;
}

export function renderFrontmatter(input: NoteInput, status: string): string {
  const { item, analysis: a } = input;
  const lines = [
    '---',
    `title: ${y(a.title)}`,
    `source: ${y(wikilink(item.path))}`,
  ];
  if (item.url) lines.push(`url: ${y(item.url)}`);
  if (item.author) lines.push(`author: ${y(item.author)}`);
  if (item.published) lines.push(`published: ${y(item.published)}`);
  lines.push(
    `verdict: ${a.verdict}`,
    `score: ${a.score}`,
    `topic: ${y(a.topic)}`,
    `type: ${a.form ?? a.type}`,
    `tags: ${yamlList(a.tags)}`,
    `status: ${status}`,
    `completeness: ${a.completeness}`,
    `confidence: ${a.confidence}`,
    `assets: ${a.assets.length}`,
    `analyzed: ${new Date(input.analyzedAt).toISOString().slice(0, 10)}`,
    `model: ${y(input.model)}`,
    'ai-curator: 1',
    '---',
  );
  return lines.join('\n');
}

function renderAssetBlock(a: Asset, t: ReturnType<typeof labels>): string[] {
  const out = [`### ${oneLine(a.name || a.kind)} · ${a.kind}`, ''];
  if (a.purpose) out.push(`${t.purpose}${t.sep}${oneLine(a.purpose)}`, '');
  if (a.usage) out.push(`${t.usage}${t.sep}${oneLine(a.usage)}`, '');
  out.push(a.kind === 'table' && a.verbatim ? a.content.trim() : fenced(a.content, fenceLang(a)), '');
  out.push(`<small>${a.verbatim ? t.verbatim : t.condensed}</small>`, '');
  return out;
}

export function renderBody(input: NoteInput): string {
  const { item, analysis: a, lang } = input;
  const t = labels(lang);
  const out: string[] = [];
  const legacy = a.v === undefined;

  // Decision block: verdict, why, what you get, the takeaway.
  const reason = a.verdict === 'skip' && a.skip_reason !== 'none' && t.skipReason[a.skip_reason]
    ? `${t.skipReason[a.skip_reason]}${t.sep}${oneLine(a.verdict_reason)}` : oneLine(a.verdict_reason);
  out.push(`> [!${CALLOUT[a.verdict]}] ${t.verdict[a.verdict]} · ${a.score}/100${reason ? ` · ${t.why}${t.sep}${reason}` : ''}`);
  if (a.payoff) out.push(`> **${t.payoff}**${t.sep}${oneLine(a.payoff)}`);
  out.push(`> ${oneLine(a.tldr)}`);
  if (a.relevance) out.push(`>`, `> ${oneLine(a.relevance)}`);
  out.push('');
  if (a.completeness !== 'full') {
    const what = a.missing ? `${t.sep}${oneLine(a.missing)}` : '';
    out.push(`> [!warning] ${t.incomplete}${what}${a.completeness === 'teaser' ? `（${t.provisional}）` : ''}`);
    if (item.recoverable === 'x') out.push(`> ${t.recoverX}`);
    out.push('');
  }
  if (legacy) out.push(`> [!note] ${t.legacy}`, '');

  out.push(`## ${t.summary}`, '', a.summary.trim(), '');

  const verbatim = a.assets.filter((x) => VERBATIM_KINDS.has(x.kind) && x.content);
  if (verbatim.length) {
    out.push(`## ${t.useNow}`, '');
    for (const asset of verbatim) out.push(...renderAssetBlock(asset, t));
  }

  const refs = a.assets.filter((x) => !VERBATIM_KINDS.has(x.kind));
  const repos = item.repos ?? [];
  if (refs.length || repos.length) {
    out.push(`## ${t.tools}`, '');
    for (const f of repos) out.push(`- ${repoLine(f, lang)}`);
    if (repos.length) out.push('');
    const shown = refs.filter((r) => !repos.some((f) => r.url && r.url.toLowerCase().replace(/\/$/, '') === f.url.toLowerCase()));
    if (shown.length) {
      out.push(`| | ${t.purpose} | ${t.usage} |`, '|---|---|---|');
      for (const r of shown) out.push(`| ${r.url ? `[${cell(r.name)}](${r.url})` : cell(r.name)} · ${r.kind} | ${cell(r.purpose)} | ${cell(r.usage)} |`);
      out.push('');
    }
  }

  if (a.knowledge.length) {
    out.push(`## ${t.keyIdeas}`, '');
    for (const k of a.knowledge) {
      const mark = k.basis === 'inferred' ? ` _(${t.inferred})_` : '';
      out.push(`- **${oneLine(k.point)}**${k.detail ? ' — ' + oneLine(k.detail) : ''}${mark}`);
      if (k.quote && k.quoteOk !== false && !legacy) out.push(`  > ${oneLine(k.quote)}`);
    }
    out.push('');
  }
  if (a.steps.length) out.push(`## ${t.howTo}`, '', a.steps.map((s, i) => `${i + 1}. ${oneLine(s)}`).join('\n'), '');

  const arg = a.argument;
  if (arg.thesis || arg.evidence.length) {
    out.push(`## ${t.argument}`, '');
    if (arg.thesis) out.push(`**${t.thesis}**${t.sep}${oneLine(arg.thesis)}`, '');
    for (const e of arg.evidence) {
      out.push(`- ${oneLine(e.claim)} · _${t.support[e.support] ?? e.support}_`);
      if (e.quote && e.quoteOk !== false) out.push(`  > ${oneLine(e.quote)}`);
    }
    if (arg.evidence.length) out.push('');
    if (arg.limitations.length) out.push(`**${t.limitations}**`, '', bullets(arg.limitations), '');
    if (arg.counterpoints.length) out.push(`**${t.counter}**`, '', bullets(arg.counterpoints), '');
  }
  if (a.applicability.length) out.push(`## ${t.applicability}`, '', bullets(a.applicability), '');
  if (a.actions.length) out.push(`## ${t.actions}`, '', bullets(a.actions, true), '');
  if (a.caveats.length) out.push(`## ${t.caveats}`, '', bullets(a.caveats), '');
  if (a.open_questions.length) out.push(`## ${t.questions}`, '', bullets(a.open_questions), '');
  if (input.related.length) {
    out.push(`## ${t.related}`, '', input.related.map((r) => '- ' + wikilink(r.path, r.title)).join('\n'), '');
  }
  const src = [`${t.source}${t.sep}${wikilink(item.path, t.original)}`];
  if (item.url) src.push(`[${t.link}](${item.url})`);
  src.push(`${t.conf}${t.sep}${t.confidence[a.confidence] ?? a.confidence}`, t.scores(a.scores));
  out.push('---', src.join(' · '), '');
  return out.join('\n');
}

/** Read the reading status a user may have edited in an existing curated note. */
export function readStatus(existing: string | null): string | undefined {
  const m = existing?.match(/^---\r?\n[\s\S]*?^status:\s*["']?(\w+)["']?\s*$/m);
  return m?.[1];
}

/** Everything the user wrote below the marker survives regeneration. */
export function userSection(existing: string | null, lang: OutputLanguage): string {
  if (existing) {
    const at = existing.indexOf(MARKER);
    if (at >= 0) return existing.slice(at + MARKER.length).replace(/^\r?\n/, '');
  }
  return `\n## ${labels(lang).myNotes}\n\n`;
}

export function renderNote(input: NoteInput, existing: string | null, status: string): string {
  return [renderFrontmatter(input, status), '', renderBody(input), MARKER, userSection(existing, input.lang)].join('\n');
}

/** Is this file something the curator wrote (safe to overwrite above the marker)? */
export function isCuratedNote(text: string): boolean {
  return /^---\r?\n[\s\S]*?^ai-curator:\s*1\s*$/m.test(text);
}

/**
 * Local, free knowledge links. Shared tools/repositories weigh most, then shared tags; a shared topic alone
 * never links two notes. Skipped items are never suggested.
 */
export function relatedItems(target: Item, all: Item[], limit = 5): Item[] {
  const a = target.analysis;
  if (!a) return [];
  const tags = new Set(a.tags);
  const names = (x: Analysis) => new Set([...x.mentions.map((m) => m.name.toLowerCase()), ...x.assets.map((m) => (m.url || m.name).toLowerCase())]);
  const mine = names(a);
  const scored: { item: Item; score: number }[] = [];
  for (const other of all) {
    const b = other.analysis;
    if (!b || other.path === target.path || !other.notePath || other.state !== 'done' || b.verdict === 'skip') continue;
    let score = 0;
    for (const tag of b.tags) if (tags.has(tag)) score += 2;
    for (const n of names(b)) if (mine.has(n)) score += 3;
    if (score && b.topic.toLowerCase() === a.topic.toLowerCase()) score += 1;
    if (score >= 3) scored.push({ item: other, score: score + b.score / 100 });
  }
  return scored.sort((x, y2) => y2.score - x.score).slice(0, limit).map((s) => s.item);
}

export interface DigestInput {
  items: Item[];
  from: number;
  to: number;
  lang: OutputLanguage;
}

export function renderDigest({ items, from, to, lang }: DigestInput): string {
  const t = labels(lang);
  const inRange = items
    .filter((i) => i.state === 'done' && i.analysis && i.notePath && (i.analyzedAt ?? 0) >= from && (i.analyzedAt ?? 0) < to)
    .sort((a, b) => b.analysis!.score - a.analysis!.score);
  const day = (ms: number) => new Date(ms).toISOString().slice(0, 10);
  const out = ['---', `title: ${y(`${t.digest} ${day(from)} – ${day(to - 1)}`)}`, 'ai-curator: 1', 'tags: [ai-curator/digest]', '---', ''];
  if (!inRange.length) return out.concat(t.empty, '').join('\n');
  const teaser = (i: Item) => i.analysis!.completeness === 'teaser';
  const read = inRange.filter((i) => i.analysis!.verdict === 'read' && !teaser(i));
  out.push(t.stats(inRange.length, read.length), '');
  const section = (title: string, list: Item[], withPayoff = true) => {
    if (!list.length) return;
    out.push(`## ${title}`, '');
    for (const i of list) {
      const a = i.analysis!;
      out.push(`- **${wikilink(i.notePath!, a.title)}** · ${a.score} · ${a.topic}`, `  ${oneLine(withPayoff && a.payoff ? `${t.payoff}${t.sep}${a.payoff}` : a.tldr)}`);
    }
    out.push('');
  };
  section(t.readNext, read);
  section(t.worthKeeping, inRange.filter((i) => i.analysis!.verdict === 'reference' && !teaser(i)));
  section(t.skimmed, inRange.filter((i) => i.analysis!.verdict === 'skim' && !teaser(i)), false);
  const missing = inRange.filter(teaser);
  if (missing.length) {
    out.push(`## ${t.needsSource}`, '');
    for (const i of missing) out.push(`- ${wikilink(i.notePath!, i.analysis!.title)}${i.analysis!.missing ? ' — ' + oneLine(i.analysis!.missing) : ''}`);
    out.push('');
  }
  const skipped = inRange.filter((i) => i.analysis!.verdict === 'skip' && !teaser(i));
  if (skipped.length) {
    out.push(`## ${t.skippedList}`, '');
    for (const i of skipped) out.push(`- ${wikilink(i.notePath!, i.analysis!.title)} — ${t.skipReason[i.analysis!.skip_reason] || oneLine(i.analysis!.verdict_reason)}`);
    out.push('');
  }
  const topics = new Map<string, number>();
  for (const i of inRange) topics.set(i.analysis!.topic, (topics.get(i.analysis!.topic) ?? 0) + 1);
  out.push('---', [...topics].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} (${v})`).join(' · '), '');
  return out.join('\n');
}

function toolboxGroup(kind: string): string {
  if (kind === 'prompt' || kind === 'template') return 'prompt';
  if (kind === 'code' || kind === 'command' || kind === 'config') return 'code';
  if (kind === 'table' || kind === 'checklist') return 'table';
  if (kind === 'repo') return 'repo';
  if (kind === 'tool') return 'tool';
  if (kind === 'paper' || kind === 'dataset') return 'paper';
  return 'resource';
}

export interface ToolboxInput { items: Item[]; lang: OutputLanguage; now: number }

/** Every reusable asset across the library, grouped by kind, each linked to the note it came from. */
export function renderToolbox({ items, lang, now }: ToolboxInput): string {
  const t = labels(lang);
  const groups = new Map<string, { asset: Asset; item: Item; facts?: RepoFacts }[]>();
  const seen = new Set<string>();
  const sources = new Set<string>();
  const usable = items.filter((i) => i.state === 'done' && i.analysis && i.notePath && i.analysis.verdict !== 'skip')
    .sort((a, b) => b.analysis!.score - a.analysis!.score);
  for (const item of usable) {
    for (const asset of item.analysis!.assets) {
      const key = (asset.url || asset.kind + ':' + asset.name + ':' + asset.content.slice(0, 80)).toLowerCase().replace(/\/$/, '');
      if (seen.has(key)) continue;
      seen.add(key);
      const facts = item.repos?.find((f) => asset.url && f.url.toLowerCase() === asset.url.toLowerCase().replace(/\/$/, ''));
      const g = toolboxGroup(asset.kind);
      if (!groups.has(g)) groups.set(g, []);
      groups.get(g)!.push({ asset, item, facts });
      sources.add(item.path);
    }
  }
  const total = [...groups.values()].reduce((n, g) => n + g.length, 0);
  const out = ['---', `title: ${y(t.toolbox)}`, 'ai-curator: 1', 'tags: [ai-curator/toolbox]', `updated: ${new Date(now).toISOString().slice(0, 10)}`, '---', '',
    `# ${t.toolbox}`, '', t.toolboxIntro(total, sources.size), ''];
  for (const g of ['prompt', 'code', 'table', 'repo', 'tool', 'resource', 'paper']) {
    const list = groups.get(g);
    if (!list?.length) continue;
    out.push(`## ${t.kinds[g]}`, '');
    for (const { asset, item, facts } of list) {
      const from = `${t.from} ${wikilink(item.notePath!, item.analysis!.title)}`;
      if (VERBATIM_KINDS.has(asset.kind)) {
        out.push(`### ${oneLine(asset.name || asset.kind)}`, '', `${asset.purpose ? oneLine(asset.purpose) + ' · ' : ''}${from}`, '');
        out.push(asset.kind === 'table' && asset.verbatim ? asset.content.trim() : fenced(asset.content, fenceLang(asset)), '');
      } else if (facts) {
        out.push(`- ${repoLine(facts, lang)}${asset.usage ? `\n  ${t.usage}${t.sep}${oneLine(asset.usage)}` : ''}\n  ${from}`);
      } else {
        out.push(`- ${asset.url ? `[${aliasText(asset.name)}](${asset.url})` : `**${oneLine(asset.name)}**`}${asset.purpose ? ' — ' + oneLine(asset.purpose) : ''} · ${from}`);
      }
    }
    out.push('');
  }
  return out.join('\n');
}

/** An Obsidian Bases file over the curated notes folder (core plugin, Obsidian 1.9+). */
export function renderBase(notesFolder: string): string {
  const folder = JSON.stringify(notesFolder);
  const order = ['file.name', 'verdict', 'score', 'topic', 'type', 'confidence', 'status', 'author', 'analyzed'];
  const view = (name: string, filters: string[]) => [
    '  - type: table',
    `    name: ${JSON.stringify(name)}`,
    ...(filters.length ? ['    filters:', '      and:', ...filters.map((f) => `        - ${JSON.stringify(f)}`)] : []),
    '    order:',
    ...order.map((o) => `      - ${o}`),
    '    sort:',
    '      - property: score',
    '        direction: DESC',
  ].join('\n');
  return [
    'filters:',
    '  and:',
    `    - ${JSON.stringify(`file.inFolder(${folder})`)}`,
    '    - \'file.ext == "md"\'',
    'views:',
    view('Read next', ['verdict == "read"', 'status == "unread"']),
    view('Unread', ['status == "unread"', 'verdict != "skip"']),
    view('All curated', []),
    view('Reference', ['verdict == "reference"']),
    view('Needs full text', ['completeness == "teaser"']),
    '',
  ].join('\n');
}
